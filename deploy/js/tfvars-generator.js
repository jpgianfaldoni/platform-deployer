(function (root, factory) {
  const api = factory(root.PlatformConfiguration || (typeof require !== 'undefined' ? require('./configuration') : null));
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.TfvarsGenerator = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function (Configuration) {
  const hclString = value => JSON.stringify(String(value));
  const hclBoolean = value => value ? 'true' : 'false';
  const hclNumber = value => String(Number(value));
  const hclList = values => `[${values.map(value => typeof value === 'number' ? hclNumber(value) : hclString(value)).join(', ')}]`;
  function hclMap(value) {
    const entries = Object.entries(value).sort(([a], [b]) => a.localeCompare(b));
    if (!entries.length) return '{}';
    const keyWidth = Math.max(...entries.map(([key]) => hclString(key).length));
    return `{\n${entries.map(([key, item]) => `  ${hclString(key).padEnd(keyWidth)} = ${hclString(item)}`).join('\n')}\n}`;
  }

  function addSection(lines, title, values) {
    const assignments = values.map(value => value.match(/^([A-Za-z0-9_]+) = ([^\n]+)$/));
    const keyWidth = Math.max(...assignments.filter(Boolean).map(match => match[1].length));
    const formatted = values.map((value, index) => {
      const match = assignments[index];
      return match ? `${match[1].padEnd(keyWidth)} = ${match[2]}` : value;
    });
    lines.push('', `# ${title}`, ...formatted);
  }

  function assignment(name, value) {
    return `${name} = ${value}`;
  }

  function generateStandard(config) {
    const managed = config.network_mode === 'managed';
    const existingMetastore = config.metastore_mode === 'existing';
    const lines = [
      '# Generated by Platform Deployer',
      '# Compatible with the pinned aws-byovpc-uc Technical Services example.'
    ];
    addSection(lines, 'Databricks configuration', [
      assignment('databricks_account_id', hclString(config.databricks_account_id)),
      assignment('prefix', hclString(config.project_prefix)),
      assignment('resource_prefix', hclString(config.resource_prefix)),
      assignment('pricing_tier', hclString(config.pricing_tier))
    ]);
    addSection(lines, 'AWS configuration', [
      assignment('aws_account_id', hclString(config.aws_account_id)),
      assignment('region', hclString(config.region)),
      assignment('tags', hclMap(config.tags))
    ]);
    addSection(lines, 'Network configuration', [
      assignment('vpc_id', hclString(managed ? '' : config.vpc_id)),
      assignment('vpc_cidr_range', hclString(config.vpc_cidr_range)),
      assignment('availability_zones', hclList(managed ? config.availability_zones : [])),
      assignment('subnet_ids', hclList(managed ? [] : config.subnet_ids)),
      assignment('private_subnets_cidr', hclList(managed ? config.private_subnets_cidr : [])),
      assignment('public_subnets_cidr', hclList(managed ? config.public_subnets_cidr : [])),
      assignment('intra_subnet_cidr', hclList(managed ? config.intra_subnet_cidr : [])),
      assignment('security_group_ids', hclList(config.security_group_ids)),
      assignment('new_security_group_name', hclString(config.new_security_group_name)),
      assignment('sg_egress_ports', hclList(config.sg_egress_ports))
    ]);
    addSection(lines, 'Unity Catalog metastore', [
      assignment('metastore_id', hclString(existingMetastore ? config.metastore_id : '')),
      assignment('metastore_name', hclString(existingMetastore ? '' : config.metastore_name))
    ]);
    addSection(lines, 'Optional catalog and validation cluster', [
      assignment('new_catalog', hclBoolean(config.new_catalog)),
      assignment('catalog_name', hclString(config.catalog_name)),
      assignment('external_location_name', hclString(config.external_location_name)),
      assignment('storage_credential_name', hclString(config.storage_credential_name)),
      assignment('new_cluster', hclBoolean(config.new_cluster)),
      assignment('cluster_autotermination_minutes', hclNumber(config.cluster_autotermination_minutes))
    ]);
    return `${lines.join('\n')}\n`;
  }

  function generatePrivateLink(config) {
    const managed = config.network_configuration !== 'custom';
    const existingMetastore = config.metastore_mode === 'existing';
    const lines = [
      '# Generated by Platform Deployer',
      '# Compatible with the pinned aws-byovpc-classic-privatelink Technical Services example.'
    ];
    addSection(lines, 'Databricks configuration', [
      assignment('databricks_account_id', hclString(config.databricks_account_id)),
      assignment('prefix', hclString(config.project_prefix)),
      assignment('resource_prefix', hclString(config.resource_prefix))
    ]);
    addSection(lines, 'AWS configuration', [
      assignment('region', hclString(config.region)),
      assignment('tags', hclMap(config.tags))
    ]);
    addSection(lines, 'Network configuration', [
      assignment('network_configuration', hclString(config.network_configuration)),
      assignment('vpc_cidr_range', hclString(config.vpc_cidr_range)),
      assignment('availability_zones', hclList(managed ? config.availability_zones : [])),
      assignment('private_subnets_cidr', hclList(managed ? config.private_subnets_cidr : [])),
      assignment('public_subnets_cidr', hclList(managed ? config.public_subnets_cidr : [])),
      ...(config.network_configuration === 'fully_private' ? [assignment('endpoint_subnet_cidr', hclString(config.endpoint_subnet_cidr))] : []),
      assignment('vpc_id', hclString(managed ? '' : config.vpc_id)),
      assignment('subnet_ids', hclList(managed ? [] : config.subnet_ids)),
      assignment('security_group_ids', hclList(managed ? [] : config.security_group_ids)),
      assignment('backend_rest_aws_vpce_id', hclString(managed ? '' : config.backend_rest_aws_vpce_id)),
      assignment('backend_relay_aws_vpce_id', hclString(managed ? '' : config.backend_relay_aws_vpce_id)),
      assignment('sg_egress_ports', hclList(config.sg_egress_ports)),
      assignment('additional_egress_ips', hclList(config.additional_egress_ips))
    ]);
    addSection(lines, 'Unity Catalog metastore', [
      assignment('metastore_id', hclString(existingMetastore ? config.metastore_id : '')),
      assignment('metastore_name', hclString(existingMetastore ? '' : config.metastore_name))
    ]);
    return `${lines.join('\n')}\n`;
  }

  function generate(input) {
    const result = Configuration.validate(input);
    if (!result.valid) throw new Error(result.errors.map(error => error.message).join(' '));
    return result.config.enable_private_link ? generatePrivateLink(result.config) : generateStandard(result.config);
  }

  return { generate, generateStandard, generatePrivateLink, hclString, hclList, hclMap };
});
